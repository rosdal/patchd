//! Repository tasks: `cargo xtask <task>`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use patchd_core::config::Config;
use patchd_core::model::ScanReport;
use patchd_core::plan::Plan;
use patchd_core::runlog::Record;
use serde_json::Value;

const USAGE: &str = "usage: cargo xtask schema";

fn main() -> ExitCode {
    if std::env::args().nth(1).as_deref() != Some("schema") {
        eprintln!("{USAGE}");
        return ExitCode::from(2);
    }
    match schema() {
        Ok(paths) => {
            for p in paths {
                println!("wrote {}", p.display());
            }
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Writes the JSON Schemas of everything the agent reports, generated from the Rust types
/// (ADR 0007), and `docs/config.md` from the config types' doc comments.
fn schema() -> std::io::Result<Vec<PathBuf>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace root");
    let schemas = [
        ("scan-report.json", schemars::schema_for!(ScanReport)),
        ("plan.json", schemars::schema_for!(Plan)),
        ("run-event.json", schemars::schema_for!(Record)),
    ];
    let mut written = Vec::new();
    for (name, schema) in schemas {
        let path = root.join("protocol/schemas").join(name);
        let json = serde_json::to_string_pretty(&schema).map_err(std::io::Error::other)?;
        std::fs::create_dir_all(path.parent().expect("schema path has a parent"))?;
        std::fs::write(&path, format!("{json}\n"))?;
        written.push(path);
    }

    let path = root.join("docs/config.md");
    let schema =
        serde_json::to_value(schemars::schema_for!(Config)).map_err(std::io::Error::other)?;
    std::fs::write(&path, config_doc(&schema))?;
    written.push(path);
    Ok(written)
}

/// `docs/config.md`: one table per section, from the schema's descriptions and defaults.
fn config_doc(schema: &Value) -> String {
    let mut out = String::from(
        "# Configuration\n\n\
         <!-- Generated by `cargo xtask schema` from crates/patchd-core/src/config.rs. Do not edit. -->\n\n\
         Patchd reads `/etc/patchd/config.toml`, or the file named with `--config`. Every key is optional; \
         a missing file means all defaults. Unknown keys are an error, so a typo never passes silently: \
         `patchd config check` validates the file and reports errors with line numbers, and \
         `patchd config show` prints the effective config.\n\n\
         Precedence, highest first: command-line flags (`--security`, `--all`), environment variables, \
         the file, the defaults. An environment variable is `PATCHD_<SECTION>_<KEY>` in capitals, such as \
         `PATCHD_APPLY_FILTER=all` or `PATCHD_APPLY_EXCLUDE='[\"docker-ce*\"]'`; its value is a TOML value, \
         and anything that does not parse as one is a string.\n\n\
         The schedule is not here: it is the `OnCalendar` of `patchd-apply.timer` \
         (see [install-linux.md](install-linux.md)).\n",
    );
    let defs = &schema["$defs"];
    let resolve = |v: &Value| -> Value {
        v.get("$ref")
            .and_then(Value::as_str)
            .and_then(|r| r.rsplit('/').next())
            .map_or_else(|| v.clone(), |name| defs[name].clone())
    };
    let Some(sections) = schema["properties"].as_object() else {
        return out;
    };
    for (section, sref) in sections {
        let def = resolve(sref);
        let _ = write!(out, "\n## `[{section}]`\n\n");
        if let Some(d) = def["description"].as_str() {
            let _ = writeln!(out, "{d}\n");
        }
        out.push_str("| Key | Type | Default | Meaning |\n| --- | --- | --- | --- |\n");
        let Some(props) = def["properties"].as_object() else {
            continue;
        };
        for (key, prop) in props {
            let resolved = resolve(prop);
            let ty = type_name(&resolved);
            let default = prop
                .get("default")
                .or_else(|| def.get("default").and_then(|d| d.get(key)))
                .map_or_else(String::new, |d| format!("`{}`", toml_literal(d)));
            let mut meaning = prop["description"]
                .as_str()
                .or_else(|| resolved["description"].as_str())
                .unwrap_or("")
                .replace('\n', " ");
            if let Some(values) = enum_values(&resolved) {
                let _ = write!(meaning, " One of {values}.");
            }
            let _ = writeln!(out, "| `{key}` | {ty} | {default} | {} |", meaning.trim());
        }
    }
    out
}

fn type_name(v: &Value) -> &'static str {
    if enum_values(v).is_some() {
        return "string";
    }
    match v["type"].as_str() {
        Some("boolean") => "boolean",
        Some("integer") => "integer",
        Some("array") => "array of strings",
        _ => "string",
    }
}

/// The allowed values of a string enum, as `` `a`, `b` ``.
fn enum_values(v: &Value) -> Option<String> {
    let values: Vec<String> = if let Some(e) = v["enum"].as_array() {
        e.iter()
            .filter_map(Value::as_str)
            .map(|s| format!("`{s}`"))
            .collect()
    } else {
        v["oneOf"]
            .as_array()?
            .iter()
            .filter_map(|o| o["const"].as_str().or_else(|| o["enum"][0].as_str()))
            .map(|s| format!("`{s}`"))
            .collect()
    };
    (!values.is_empty()).then(|| values.join(", "))
}

fn toml_literal(v: &Value) -> String {
    match v {
        Value::String(s) => format!("\"{s}\""),
        Value::Array(a) if a.is_empty() => "[]".to_owned(),
        other => other.to_string(),
    }
}
