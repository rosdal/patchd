// Command targets scans the vulnerable integration targets and the reference
// repos, scores them against eval/targets/expected/*.yaml and
// eval/triage/<version>.yaml, and writes a summary report. It exits 1 when
// the milestone gate fails: an in-scope issue was missed, or a finding is
// untriaged.
//
//	go run ./eval/cmd/targets                    # the vulnerable targets
//	go run ./eval/cmd/targets -reference         # plus every reference repo
//	go run ./eval/cmd/targets -report eval/reports/v0.4-targets.md
//
// pnpm eval:targets runs it. The repos must be fetched (pnpm targets:fetch).
package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/patchd/patchd/engine"
	"github.com/patchd/patchd/engine/rules"
	"github.com/patchd/patchd/eval/harness"
)

func main() {
	version := flag.String("version", "v0.4", "the version whose scope gates the run")
	reference := flag.Bool("reference", false, "also scan every reference repo and report precision per rule")
	only := flag.String("repos", "", "comma-separated repo IDs to scan (default: the targets, plus the reference repos with -reference)")
	report := flag.String("report", "", "write the Markdown summary here")
	flag.Parse()
	if err := run(*version, *reference, *only, *report); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// vulnerable are the deliberately vulnerable apps: their findings score
// against expected lists and are reported apart from precision on real code.
var vulnerable = []string{"dvna", "juice-shop", "nodegoat"}

func run(version string, reference bool, only, reportPath string) error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	triage, err := harness.LoadTriage(filepath.Join(root, "eval", "triage", version+".yaml"))
	if err != nil {
		return err
	}
	files, err := harness.ExpectedFiles(root)
	if err != nil {
		return err
	}
	expected := map[string]harness.Expected{}
	for _, f := range files {
		e, err := harness.LoadExpected(f)
		if err != nil {
			return err
		}
		expected[e.Repo] = e
	}
	repos := slices.Clone(vulnerable)
	if reference {
		ids, err := referenceRepos(filepath.Join(root, "eval", "targets", "reference-repos.yaml"))
		if err != nil {
			return err
		}
		for _, id := range ids {
			if !slices.Contains(repos, id) {
				repos = append(repos, id)
			}
		}
	}
	if only != "" {
		repos = strings.Split(only, ",")
	}

	var (
		scores    []harness.TargetScore
		realCode  []harness.Classified // findings on the non-vulnerable repos
		vulnCode  []harness.Classified // unexpected findings on the vulnerable apps
		repoLines []string
		gate      = true
	)
	for _, repo := range repos {
		dir := filepath.Join(root, ".patchd", "targets", repo)
		if _, err := os.Stat(dir); err != nil {
			return fmt.Errorf("%s: not fetched (pnpm targets:fetch %s)", repo, repo)
		}
		start := time.Now()
		res, err := engine.Analyze(context.Background(), dir, engine.Options{Rules: rules.IDs()})
		if err != nil {
			return fmt.Errorf("%s: %w", repo, err)
		}
		fmt.Fprintf(os.Stderr, "%-18s %5d files %8d lines %4d findings  %s\n", repo, res.Stats.Files, res.Stats.Lines, len(res.Findings), time.Since(start).Round(100*time.Millisecond))
		repoLines = append(repoLines, fmt.Sprintf("| %s | %d | %d | %d | %s |", repo, res.Stats.Files, res.Stats.Lines, len(res.Findings), res.Stats.Elapsed.Round(100*time.Millisecond)))
		if exp, ok := expected[repo]; ok {
			s, err := harness.ScoreTarget(exp, res.Findings, triage, version)
			if err != nil {
				return err
			}
			scores = append(scores, s)
			gate = gate && s.GatePassed()
			vulnCode = append(vulnCode, s.Unexpected...)
			continue
		}
		cs := harness.Classify(repo, res.Findings, triage)
		for _, c := range cs {
			if c.Triage == nil {
				gate = false
			}
		}
		realCode = append(realCode, cs...)
	}

	var out strings.Builder
	writeReport(&out, version, scores, repoLines, realCode, vulnCode, reference || only != "", gate)
	fmt.Print(out.String())
	if reportPath != "" {
		if err := os.WriteFile(reportPath, []byte(out.String()), 0o644); err != nil { //nolint:gosec // a report for the repo
			return err
		}
	}
	if !gate {
		return fmt.Errorf("%s gate failed: an in-scope issue was missed or a finding is untriaged (eval/triage/%s.yaml)", version, version)
	}
	return nil
}

func writeReport(w io.Writer, version string, scores []harness.TargetScore, repoLines []string, realCode, vulnCode []harness.Classified, precision, gate bool) {
	p := func(format string, args ...any) { _, _ = fmt.Fprintf(w, format, args...) }
	p("# Integration targets, %s\n\n", version)
	p("Generated by `pnpm eval:targets`; every rule ran, including those off by default.\n\n")
	p("## Vulnerable targets\n\n")
	p("| Target | Found (%s scope) | Missed (%s scope) | Expected misses (later scope) | Found early | Unexpected (triaged) |\n", version, version)
	p("| --- | ---: | ---: | ---: | ---: | ---: |\n")
	for _, s := range scores {
		triaged := 0
		for _, u := range s.Unexpected {
			if u.Triage != nil {
				triaged++
			}
		}
		p("| %s | %d | %d | %d | %d | %d (%d) |\n", s.Repo, len(s.Found), len(s.Missed), len(s.Later), len(s.Early), len(s.Unexpected), triaged)
	}
	for _, s := range scores {
		for _, m := range s.Missed {
			p("\n- **Missed** %s %s:%d (%s)", m.Rule, m.File, m.Line, s.Repo)
		}
		for _, l := range s.Later {
			p("\n- Expected miss until %s: %s %s:%d (%s)", l.Scope, l.Rule, l.File, l.Line, s.Repo)
		}
	}
	p("\n\n")
	ruleIDs := rules.IDs()
	p("Unexpected findings on the vulnerable targets, by rule:\n\n")
	precisionTable(p, ruleIDs, vulnCode)
	if precision {
		p("\n## Precision on real code\n\n")
		p("The reference repos other than the vulnerable apps, triaged in `eval/triage/%s.yaml`. The gate is 80%% true positives per rule; below it the rule ships off by default.\n\n", version)
		precisionTable(p, ruleIDs, realCode)
	}
	p("\n## Repos\n\n| Repo | Files | Lines | Findings | Time |\n| --- | ---: | ---: | ---: | ---: |\n")
	for _, l := range repoLines {
		p("%s\n", l)
	}
	verdict := "passed"
	if !gate {
		verdict = "**failed**"
	}
	p("\nGate (%s): %s.\n", version, verdict)
}

func precisionTable(p func(string, ...any), ruleIDs []string, cs []harness.Classified) {
	p("| Rule | True positives | False positives | Unclear | Untriaged | Precision |\n| --- | ---: | ---: | ---: | ---: | ---: |\n")
	for _, pr := range harness.PrecisionByRule(ruleIDs, cs) {
		value := "no findings"
		if v := pr.Value(); v >= 0 {
			value = fmt.Sprintf("%.0f%%", 100*v)
		}
		p("| %s | %d | %d | %d | %d | %s |\n", pr.Rule, pr.TP, pr.FP, pr.Unclear, pr.Untri, value)
	}
}

// referenceRepos reads the ids from reference-repos.yaml (a flat list; the
// same line format tools/scripts/lib/targets.mjs reads).
func referenceRepos(path string) ([]string, error) {
	data, err := os.ReadFile(path) //nolint:gosec // a repo file
	if err != nil {
		return nil, err
	}
	var ids []string
	for _, line := range strings.Split(string(data), "\n") {
		if id, ok := strings.CutPrefix(strings.TrimSpace(line), "- id:"); ok {
			ids = append(ids, strings.TrimSpace(id))
		}
	}
	return ids, nil
}
